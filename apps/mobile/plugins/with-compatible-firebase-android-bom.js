const { withProjectBuildGradle } = require('expo/config-plugins');

const firebaseAndroidBomVersion = '34.12.0';
const firebaseAndroidBomBlockPattern =
  /\/\/ @generated by with-compatible-firebase-android-bom[\s\S]*?\/\/ @end generated/;
const firebaseAndroidBomBlock = `// @generated by with-compatible-firebase-android-bom
project.ext {
  set('react-native', [
    versions: [
      firebase: [
        bom: "${firebaseAndroidBomVersion}"
      ]
    ]
  ])
}
// @end generated`;

module.exports = function withCompatibleFirebaseAndroidBom(expoConfig) {
  return withProjectBuildGradle(expoConfig, (config) => {
    if (firebaseAndroidBomBlockPattern.test(config.modResults.contents)) {
      config.modResults.contents = config.modResults.contents.replace(
        firebaseAndroidBomBlockPattern,
        firebaseAndroidBomBlock,
      );
    } else {
      config.modResults.contents = `${firebaseAndroidBomBlock}\n\n${config.modResults.contents}`;
    }

    return config;
  });
};
